test('concurrent editors preserve drafts on conflict and cannot resurrect a wiped revision',async({page,context})=>{
  test.skip(process.env.PLAYWRIGHT_PRODUCTION_SERVER==='true','Local preparation is intentionally unavailable in production.');
  const other=await context.newPage();
  for(const tab of [page,other]){await tab.goto('/ko/personal-tools-preview');await expect(tab.getByLabel('패턴 이름',{exact:true})).toBeEnabled();}
  await page.getByLabel('패턴 이름',{exact:true}).fill('첫 창 패턴');await page.getByRole('button',{name:'패턴 추가',exact:true}).click();
  await expect(page.getByRole('option',{name:'첫 창 패턴',exact:true})).toHaveCount(1);
  await other.getByLabel('패턴 이름',{exact:true}).fill('보존할 입력');await other.getByRole('button',{name:'패턴 추가',exact:true}).click();
  await expect(other.getByRole('status')).toContainText('다른 창에서 자료가 바뀌었습니다.');
  await expect(other.getByLabel('패턴 이름',{exact:true})).toHaveValue('보존할 입력');
  await other.getByRole('button',{name:'최신 자료 다시 읽기',exact:true}).click();
  await expect(other.getByRole('option',{name:'첫 창 패턴',exact:true})).toHaveCount(1);
  // Wipe commits a new opaque tombstone even though the next state is empty.
  await page.getByLabel('전체 삭제하려면 DELETE PERSONAL TOOLS 입력',{exact:true}).fill('DELETE PERSONAL TOOLS');
  await page.getByRole('button',{name:'개인 도구 전체 삭제',exact:true}).click();await expect(page.getByRole('option',{name:'첫 창 패턴',exact:true})).toHaveCount(0);
  await other.getByRole('button',{name:'패턴 추가',exact:true}).click();
  await expect(other.getByRole('status')).toContainText('다른 창에서 자료가 바뀌었습니다.');
  await expect(other.getByLabel('패턴 이름',{exact:true})).toHaveValue('보존할 입력');
  await page.reload();await expect(page.getByLabel('패턴 이름',{exact:true})).toBeEnabled();
  await expect(page.getByRole('option',{name:'보존할 입력',exact:true})).toHaveCount(0);
});

